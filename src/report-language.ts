export type ReportLanguage = 'ja' | 'en';
export type ReportText = keyof typeof english;

/** Only own entries in application-owned display tables are meaningful codes. */
export function displayValue<T>(values: Readonly<Record<string, T>>, code: string, fallback: NoInfer<T>): T {
  return Object.hasOwn(values, code) ? values[code] : fallback;
}

export function parseReportLanguage(value: unknown): ReportLanguage {
  if (value === undefined || value === 'ja') return 'ja';
  if (value === 'en') return 'en';
  throw new SafeError('invalid_report_language');
}

export function reportText(language: ReportLanguage, value: ReportText): string {
  const selected = parseReportLanguage(language);
  if (!Object.hasOwn(english, value)) throw new SafeError('invalid_report_text');
  return selected === 'ja' ? value : english[value];
}

