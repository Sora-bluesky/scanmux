/** Saved diagnostics are untrusted; only fixed rule codes and numeric request sequences enter display text. */
export function aiTransportFailures(execution: unknown): { sequence: number; failureCode: string }[] {
  if (typeof execution !== 'object' || execution === null || !('transportRequests' in execution) || !Array.isArray(execution.transportRequests)) return [];
  const failures: { sequence: number; failureCode: string }[] = [];
  for (const row of execution.transportRequests) {
    if (typeof row !== 'object' || row === null || !('sequence' in row) || !('failureCode' in row)) continue;
    if (typeof row.sequence === 'number' && Number.isSafeInteger(row.sequence) && row.sequence > 0
      && typeof row.failureCode === 'string' && transportFailureCodes.has(row.failureCode)) failures.push({ sequence: row.sequence, failureCode: row.failureCode });
  }
  return failures;
}

/** A controlled summary; scanner diagnostics and arbitrary unit keys never enter text output. */
export function trivyCoverageText(run: EngineRun, language: ReportLanguage = 'ja'): string {
  const text = (value: ReportText) => reportText(language, value);
  if (run.engine !== 'trivy') return '';
  const coverage = run.trivyCoverage;
  if (!coverage) return text('検査範囲の受領記録がありません。');
  const states: Record<string, ReportText> = { analyzed: '対象範囲を検査', unsupported: '未対応', partial: '一部のみ検査', parse_failed: '構文解析失敗', excluded: '除外', unresolved: '未解決' };
  const summary = `${text('範囲')}: ${text(displayValue(states, coverage.state, '未確認'))}`;
  if (coverage.state === 'unsupported') return `${summary}; ${text('受領記録数')}: 0`;
  const counts = ['analyzed', 'unsupported', 'parse_failed', 'excluded', 'unresolved'].map(state => `${text(states[state])}: ${coverage.receipts.filter(receipt => receipt.state === state).length}`).join(', ');
  return `${summary}; ${text('受領記録数')}: ${coverage.receipts.length} (${counts})${coverage.state === 'partial' ? `; ${text('範囲の理由数')}: ${coverage.reasons.length}` : ''}`;
}
